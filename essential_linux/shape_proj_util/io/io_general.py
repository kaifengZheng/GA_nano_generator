def read_xyz(name):
    "read xyz data generated from ocito or python."
    with open(name,'r') as file1:
        fileline=file1.readlines()[2:]
    data = []
    ele_num = []
    for line in fileline:
            value=line.split()[1:]
            ele=line.split()[0]
            data.append([np.double(value[0]),np.double(value[1]),np.double(value[2])])
            ele_num.append(ele)
    return ele_num, np.array(data)

def write_xyz(fileobj, images, comment='', fmt='%22.15f'):
    comment = comment.rstrip()
    if '\n' in comment:
        raise ValueError('Comment line should not have line breaks.')

    natoms = len(images.positions)
    fileobj.write('%d\n%s\n' % (natoms, comment))
    for s, (x, y, z) in zip(images.symbols, images.positions):
        fileobj.write('%-2s %s %s %s\n' % (s, fmt % x, fmt % y, fmt % z))


def sort_filename(filename_partten):
    "sort xyz files generated by lammps and ovito"
    xyz_files=glob.glob(filename_partten)
    sort_file=dict()
    for i in range(0,len(xyz_files)):
        sort_file[int(xyz_files[i].split('.')[0].split('_')[1])]=xyz_files[i]
    files=[]
    for i in sorted(sort_file.keys()):
        files.append(sort_file[i])
    return files


def dir_list(dir):
    """
    only show subdirectories
    :param dir:
    :return: dirlist
    """
    dirlist = []
    for it in os.scandir(dir):
        if it.is_dir():
            dirlist.append(it.path)
    return dirlist

