def writing_xyz(coords,atom_type,path,n=1) :
    """
    the goal of writing_xyz is to write xyz file according to the positions of
    atoms from a cluster.
    :param coords: positions of atoms
    :param atom_type: atom type: eg:'Pt','Cu','Ni'
    :param n: the index of file in the file list (sometimes, we need to generate many files of same
               shapes, for example: different sizes of particles of same shape.)
    :param path: the directory name (indicate the shape of particles)
    :param name: name of file. In this case particle shape.
    """
    c = list(coords)
    #if not os.path.isfile(path):
    #    makedir(path)
    with open(path+'/'+path+str(n)+".xyz",'w') as file1:
        file1.write(str(len(c))+'\n')
        file1.write(str('0 '+'0 '+'0 ')+str('\n'))
        for i in range(len(c)):
            strr = atom_type + str(" ")+str(c[i][0])+str(" ")+str(c[i][1])+str(" ")+str(c[i][2])+str("\n")
            file1.write(strr)

        
def atom2pymat_cif(atoms,filename):
    """
    Convert ase atoms object to pymatgen structure object and write to cif file

    Args:
        atoms (ase.Atoms): ase atoms object
        filename (str): filename for cif file:
        eg: filename="task1_distorted_structures//KMgCl3_"+str(k)+".cif"
    """
    structure=AseAtomsAdaptor.get_structure(atoms)
    CifWriter(structure).write_file(filename)   
def read_xyz2atoms(filename,viewer='ase',plot=True)->Atoms:
    """
    Note: cannot use x3d viewer in jupyter notebook
    """
    atom_txt=read_xyz(filename)
    atoms=Atoms(positions=atom_txt[1],symbols=atom_txt[0])
    if plot==True:
        view(atoms,viewer=viewer)
    return atoms